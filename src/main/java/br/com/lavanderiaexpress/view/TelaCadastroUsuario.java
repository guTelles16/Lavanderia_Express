    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        char[] senha = txtSenha.getPassword();
        char[] confirma = txtConfirma.getPassword();
        try {
            if (!Arrays.equals(senha, confirma)) {
                lblMensagem.setText("As senhas não conferem.");
                return;
            }
            service.cadastrar(txtNome.getText(), txtEmail.getText(), senha);
            javax.swing.JOptionPane.showMessageDialog(this, "Conta criada! Faça seu login.");
            dispose();
        } catch (IllegalArgumentException e) {
            lblMensagem.setText(e.getMessage());
        } catch (SQLException e) {
            lblMensagem.setText("Não foi possível acessar o banco de dados.");
        } finally {
            Arrays.fill(senha, '\0');
            Arrays.fill(confirma, '\0');
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

