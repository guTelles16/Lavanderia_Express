    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
        lblMensagem.setText(" ");
        char[] senha = txtSenha.getPassword();
        try {
            Optional<Usuario> usuario = service.autenticar(txtEmail.getText(), senha);
            if (usuario.isPresent()) {
                new TelaPrincipal(usuario.get()).setVisible(true);
                dispose();
            } else {
               lblMensagem.setText("E-mail ou senha inválidos.");
               txtSenha.setText("");
            }
        } catch (SQLException e) {
            lblMensagem.setText("Não foi possível acessar o banco de dados.");
        } finally {
            Arrays.fill(senha, '\0'); // apaga a senha da memória
        }
    }//GEN-LAST:event_btnEntrarActionPerformed

