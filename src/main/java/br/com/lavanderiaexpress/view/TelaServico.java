    // Métodos de apoio
    private void configurarTabela() {
       modelo = new DefaultTableModel(new Object[]{"ID", "Descrição", "Preço Unitário"}, 0) {
           @Override
           public boolean isCellEditable(int linha, int coluna) {
               return false;
           }
       };
       tblServicos.setModel(modelo);
       tblServicos.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
       tblServicos.getSelectionModel().addListSelectionListener(e -> {
           if (!e.getValueIsAdjusting()) {
               carregarSelecionado();
           }
       });
    }
    
    private void carregarTabela() {
        try {
            List<Servico> lista = service.listar(txtBusca.getText());
            modelo.setRowCount(0);
            for (Servico s : lista) {
                modelo.addRow(new Object[]{s.id(), s.descricao(), s.precoUnitario()});
            }
        } catch (SQLException e) {
            mostrar("Não foi possível carregar os serviços.", true);
        }
    }
    
    private void carregarSelecionado() {
        int linha = tblServicos.getSelectedRow();
        if (linha < 0) {
            return;
        }
        idSelecionado = (int) modelo.getValueAt(linha, 0);
        txtDescricao.setText((String) modelo.getValueAt(linha, 1));
        
        // Recupera o BigDecimal e formata para o padrão brasileiro
        BigDecimal precoUnitario = (BigDecimal) modelo.getValueAt(linha, 2);
        txtPrecoUnitario.setText(formatarBigDecimalParaTela(precoUnitario));
        
        btnExcluir.setEnabled(true);
    }
    
    private void limparFormulario() {
        idSelecionado = 0;
        txtDescricao.setText("");
        txtPrecoUnitario.setText("");
        tblServicos.clearSelection();
        btnExcluir.setEnabled(false);
        txtDescricao.requestFocusInWindow();
    }
    
    private void mostrar(String texto, boolean erro) {
        lblMensagem.setForeground(erro ? java.awt.Color.RED : new java.awt.Color(0, 128, 0));
        lblMensagem.setText(texto);
    }
    
    // Exibir o BigDecimal com vírgula e duas casas decimais
    private String formatarBigDecimalParaTela(BigDecimal valor) {
        if (valor == null) {
            return "0,00";
        }
        DecimalFormatSymbols simbolos = new DecimalFormatSymbols(new Locale("pt", "BR"));
        DecimalFormat df = new DecimalFormat("#,##0.00", simbolos);
        return df.format(valor);
    }

