    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        try {
            if (idSelecionado == 0) {
                service.cadastrar(txtDescricao.getText(), txtPrecoUnitario.getText());
                carregarTabela();
                limparFormulario();
                mostrar("Serviço cadastrado com sucesso.", false);
            } else {
                service.atualizar(idSelecionado, txtDescricao.getText(), txtPrecoUnitario.getText());
                carregarTabela();
                limparFormulario();
                mostrar("Serviço atualizado com sucesso.", false);
            }
        } catch (IllegalArgumentException e) {
            mostrar(e.getMessage(), true);
        } catch (ParseException e) {
            mostrar(e.getMessage(), true);
        } catch (SQLException e) {
            mostrar("Não foi possível acessar o banco de dados.", true);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int opcao = JOptionPane.showConfirmDialog(this,
                "Excluir o serviço selecionado?", "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION);
        if (opcao != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            service.excluir(idSelecionado);
            carregarTabela();
            limparFormulario();
            mostrar("Serviço excluído.", false);
        } catch (IllegalArgumentException e) {
            mostrar(e.getMessage(), true);
        } catch (SQLException e) {
            mostrar("Não foi possível acessar o banco de dados.", true);
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

