    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        try {
            int indice = cmbServico.getSelectedIndex();
            if (indice < 0) {
                throw new IllegalArgumentException("Selecione um serviço.");
            }
            int quantidade = PedidoService.lerQuantidade(txtQtd.getText());
            Servico s = servicos.get(indice);
            itens.add(new ItemPedido(s.id(), s.descricao(), quantidade, s.precoUnitario()));
            atualizarTabela();
            txtQtd.setText("1");
            mostrar(" ", false);
        } catch (IllegalArgumentException e) {
            mostrar(e.getMessage(), true);
        } 
    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverActionPerformed
        int linha = tblItens.getSelectedRow();
        if (linha < 0) {
            mostrar("Selecione um item na tabela.", true);
            return;
        }
        itens.remove(linha);
        atualizarTabela();
        mostrar(" ", false);
    }//GEN-LAST:event_btnRemoverActionPerformed

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
            int indice = cmbCliente.getSelectedIndex();
            if (indice < 0) {
                throw new IllegalArgumentException("Selecione um cliente.");
            }
            BigDecimal total = PedidoService.calcularTotal(itens);
            int numero = pedidoService.registrar(clientes.get(indice), itens);
            JOptionPane.showMessageDialog(this,
                    "Pedido n° " + numero + " registrado!\nTotal: " + moeda.format(total));
            itens.clear();
            atualizarTabela();
            mostrar(" ", false);
        } catch (IllegalArgumentException e) {
            mostrar(e.getMessage(), true);
        } catch (SQLException e) {
            logger.log(java.util.logging.Level.SEVERE, "Erro ao registrar pedido", e);
            mostrar("Não foi possível registrar o pedido.", true);
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

