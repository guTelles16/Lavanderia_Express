    // Métodos de apoio
    private void configurarTabela() {
        modelo = new DefaultTableModel(
                new Object[]{"Serviço", "Qtd", "Preço unit.", "Subtotal"}, 0) {
            @Override
            public boolean isCellEditable(int linha, int coluna) {
                return false;
            }
        };
        tblItens.setModel(modelo);
        tblItens.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    }
    
    // Guardam só o texto de cada opção
    private void carregarCombos() {
        try {
            clientes = clienteService.listar("");
            servicos = servicoService.listar("");
            
            cmbCliente.removeAllItems();
            for (Cliente c : clientes) {
                cmbCliente.addItem(c.nome() + " - " + c.telefone());
            }
            cmbServico.removeAllItems();
            for (Servico s : servicos) {
                cmbServico.addItem(s.descricao() + " - " + moeda.format(s.precoUnitario()));
            }
        } catch (SQLException e) {
            mostrar("Não foi possível carregar clientes e serviços.", true);
        }
    }
    
    private void atualizarTabela() {
        modelo.setRowCount(0);
        for (ItemPedido i : itens) {
            modelo.addRow(new Object[]{
                    i.descricao(), i.quantidade(),
                    moeda.format(i.precoUnitario()), moeda.format(i.subtotal())});
        }
        lblTotal.setText("Total: " + moeda.format(PedidoService.calcularTotal(itens)));
    }
    
    private void mostrar(String texto, boolean erro) {
        lblMensagem.setForeground(erro ? java.awt.Color.RED : new java.awt.Color(0, 128, 0));
        lblMensagem.setText(texto);
    }
    
